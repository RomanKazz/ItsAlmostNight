"""Bake fence-matching gate upgrades, preserving the authored hinge and colliders.

Run from the repository root. Two overlays per level: moving door and fixed post.
"""
from pathlib import Path

from upgrade_mesh import Geometry, GlbAsset

asset = GlbAsset(Path('assets/models/construction/walls/gate.glb'))
WOOD = (215, 108, 43)
STEEL = (151, 173, 183)
GOLD = (242, 188, 45)


def post(g, x, level):
    # Dimensions and large binding bands match generate_wall_upgrades.py.
    foot_top = .079 if level == 8 else .086
    g.box((x, foot_top/2, 0), (.150, foot_top, .150), STEEL, bevel=.08)
    if level >= 4:
        bottom = .113 if level == 8 else .098
        intervals = [(bottom, .393), (.437, .452)] if level >= 5 else [(.098, .452)]
        for lo, hi in intervals:
            g.box((x, (lo+hi)/2, 0), (.148, hi-lo, .148), WOOD, bevel=.08)
    if level >= 5:
        g.box((x, .415, 0), (.162, .044, .162), GOLD, bevel=.08)
    if level >= 7:
        bottom = .5045 if level == 8 else .485
        g.box((x, (bottom+.545)/2, 0), (.170, .545-bottom, .170), STEEL, bevel=.12)
    if level == 8:
        g.box((x, .482, 0), (.178, .045, .178), GOLD, bevel=.12)
        g.box((x, .096, 0), (.160, .034, .160), GOLD, bevel=.08)


bounds = []
for level in range(2, 9):
    door, pillar = Geometry(), Geometry()
    post(door, -.436, level)
    post(pillar, .436, level)
    if 3 <= level < 6:
        door.box((0, .163, 0), (.722, .100, .090), WOOD, bevel=.08)
    if level >= 6:
        door.box((0, .200, 0), (.722, .185, .096), WOOD, bevel=.08)
    for part, suffix in ((door, 'door'), (pillar, 'pillar')):
        # The same joint limit as fences leaves clearance to neighboring cells.
        for i in range(0, len(part.positions), 3):
            part.positions[i] = max(-.501, min(.501, part.positions[i]))
        bounds.append(part.bounds())
        part.append(asset, f'upgrade_gate_l{level}_{suffix}')

total = asset.write()


def vec(v):
    return '{' + ', '.join(f'{x:.6f}F' for x in v) + '}'


header = '''#pragma once

#include <raylib.h>
#include <raymath.h>

#include <algorithm>
#include <array>

namespace ian::gate_model_detail {

inline constexpr int DoorMeshIndex = 0;
inline constexpr float DoorHingeX = -0.436F;
inline constexpr float OpenAngle = -PI * 0.5F;

[[nodiscard]] inline Matrix doorHingeTransform(float openAmount) {
    // The sign selects which side of the gate the door swings towards.
    const float clamped = std::clamp(openAmount, -1.0F, 1.0F);
    return MatrixMultiply(
        MatrixTranslate(-DoorHingeX, 0.0F, 0.0F),
        MatrixMultiply(
            MatrixRotateY(OpenAngle * clamped),
            MatrixTranslate(DoorHingeX, 0.0F, 0.0F)));
}

// Generated by tools/generate_gate_upgrades.py, after collider removal.
// Original door/fixed post are 0/1, then two overlays per level.
inline constexpr int MeshCount = 16;
inline constexpr std::array<BoundingBox, 14> UpgradeBounds{{
'''
header += ''.join('    {' + vec(a) + ', ' + vec(b) + '},\n' for a, b in bounds)
header += '''}};

template <typename Emit>
void forEachUpgradePart(int requestedLevel, Emit&& emit) {
    const int level = std::clamp(requestedLevel, 1, 8);
    if (level == 1) return;
    const int door = 2 + (level - 2)*2;
    emit(door, true);
    emit(door + 1, false);
}

[[nodiscard]] inline BoundingBox partBounds(int meshIndex) {
    return UpgradeBounds[static_cast<std::size_t>(meshIndex - 2)];
}

} // namespace ian::gate_model_detail
'''
Path('src/graphics/GateModel.hpp').write_text(header)
print(f'Baked seven gate levels: {total} bytes, two extra draws per gate.')
