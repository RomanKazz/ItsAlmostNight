"""Bake simple orange/steel/gold spike trap upgrades, preserving authored data.

Two meshes per level: socket plate and replacement spikes that retract together.
"""
import math
from pathlib import Path

from upgrade_mesh import Geometry, GlbAsset

asset = GlbAsset(Path('assets/models/traps/spike_trap.glb'))
STEEL = (151, 173, 183)
ORANGE = (245, 92, 12)
GOLD = (242, 188, 45)
DARK_STEEL = (54, 80, 94)


def rim(g, outer, inner, bottom, top, color):
    # A chamfered square frame leaves the original trap plate visible.
    def points(r, y):
        bevel = .035
        return [(x, y, z) for x, z in
                [(-r+bevel, -r), (r-bevel, -r), (r, -r+bevel),
                 (r, r-bevel), (r-bevel, r), (-r+bevel, r),
                 (-r, r-bevel), (-r, -r+bevel)]]
    lo, hi = points(outer, bottom), points(outer, top)
    inside_lo, inside_hi = points(inner, bottom), points(inner, top)
    for i in range(8):
        j = (i+1) % 8
        g.face([lo[i], hi[i], hi[j], lo[j]], color)
        g.face([inside_lo[j], inside_hi[j], inside_hi[i], inside_lo[i]], color)
        g.face([hi[i], inside_hi[i], inside_hi[j], hi[j]], color)
        g.face([lo[j], inside_lo[j], inside_lo[i], lo[i]], color)


def spike(g, x, z, radius, top, level):
    def points(r, y):
        return [(x+r*math.cos(i*math.pi/4), y, z+r*math.sin(i*math.pi/4))
                for i in range(8)]
    foot_top = .145 if level >= 5 else .170
    rings = [points(radius, .09435), points(radius*.66, foot_top),
             points(.007 if level >= 7 else .010, top)]
    for layer in range(2):
        color = GOLD if level >= 5 and layer == 0 else STEEL
        for i in range(8):
            j = (i+1) % 8
            g.face([rings[layer][i], rings[layer+1][i],
                    rings[layer+1][j], rings[layer][j]], color)
    g.face(list(reversed(rings[-1])), STEEL)
    g.face(rings[0], GOLD if level >= 5 else STEEL)


heights = [.28305, .28305, .300, .315, .315, .335, .350, .365]
bounds = []
for level in range(2, 9):
    base, spikes = Geometry(), Geometry()
    # Reinforced plate, individual sockets and broad corner blocks instead
    # of stacking thin rectangular borders around the original four spikes.
    rim(base, .405, .370, .020, .075, STEEL)
    base.box((0, .098, 0), (.735, .015, .735), DARK_STEEL, bevel=.10)
    cap_size = .11 + (level - 2) * .004
    cap_height = .025 + (level - 2) * .004
    for x in (-.349, .349):
        for z in (-.349, .349):
            base.box((x, .091 + cap_height / 2, z),
                     (cap_size, cap_height, cap_size),
                     GOLD if level >= 7 else ORANGE if level >= 3 else STEEL, bevel=.18)
    if level >= 4:
        for x in (-.391, .391):
            base.box((x, .069, 0), (.044, .074, .53), ORANGE, bevel=.15)
    if level >= 6:
        for z in (-.391, .391):
            base.box((0, .069, z), (.53, .074, .044), ORANGE, bevel=.15)
    if level == 8:
        for x in (-.390, .390):
            base.box((x, .11, 0), (.046, .018, .53), GOLD, bevel=.15)
        for z in (-.390, .390):
            base.box((0, .11, z), (.53, .018, .046), GOLD, bevel=.15)
    radius = .090 if level < 5 else (.102 if level >= 7 else .095)
    slots = [(x, z) for x in (-.225, .225) for z in (-.225, .225)]
    if level >= 3:
        slots.append((0, 0))
    if level >= 5:
        slots.extend([(-.225, 0), (.225, 0), (0, -.225), (0, .225)])
    for x, z in slots:
        base.ring(1, (x, .112, z), radius + .015, radius * .70,
                  .016, GOLD if level >= 5 else STEEL, segments=8)
        spike(spikes, x, z, radius, heights[level-1], level)
    for part, suffix in ((base, 'base'), (spikes, 'spikes')):
        bounds.append(part.bounds())
        part.append(asset, f'upgrade_spike_l{level}_{suffix}')

total = asset.write()


def vec(v):
    return '{' + ', '.join(f'{x:.6f}F' for x in v) + '}'


header = '''#pragma once

#include <raylib.h>

#include <algorithm>
#include <array>

namespace ian::spike_trap_model_detail {

// Generated by tools/generate_spike_trap_upgrades.py. Original base/spikes: 0/1.
inline constexpr int MeshCount = 16;
inline constexpr std::array<float, 8> SpikeHeights{'''
header += ', '.join(f'{v:.6f}F' for v in heights) + '};\n'
header += 'inline constexpr std::array<BoundingBox, 14> UpgradeBounds{{\n'
header += ''.join('    {' + vec(a) + ', ' + vec(b) + '},\n' for a, b in bounds)
header += '''}};

[[nodiscard]] inline int baseMeshIndex(int requestedLevel) {
    return 2 + (std::clamp(requestedLevel, 2, 8) - 2)*2;
}

[[nodiscard]] inline float hiddenOffset(int requestedLevel) {
    // Keep tips at the original resting height, even as deployed spikes grow.
    const int level = std::clamp(requestedLevel, 1, 8);
    return .13305F - SpikeHeights[static_cast<std::size_t>(level - 1)];
}

[[nodiscard]] inline float spikeOffset(int level, float seconds) {
    float exposure = 0.0F;
    // Preserve the authored cycle: 0.2 s rise, 0.8 s hold, 0.2 s retract.
    if (seconds >= 0.0F && seconds < 1.2F) {
        const auto ease = [](float t) {
            const float rise = t*t*t;
            const float fall = (1-t)*(1-t)*(1-t);
            return rise / std::max(rise + fall, .0001F);
        };
        if (seconds < .2F) exposure = ease(seconds/.2F);
        else if (seconds < 1.0F) exposure = 1.0F;
        else exposure = 1.0F - ease(std::clamp((seconds-1.0F)/.2F, 0.0F, 1.0F));
    }
    return hiddenOffset(level) * (1.0F - exposure);
}

[[nodiscard]] inline BoundingBox partBounds(int meshIndex) {
    return UpgradeBounds[static_cast<std::size_t>(meshIndex - 2)];
}

[[nodiscard]] inline float spikeScale(int level, float seconds) {
    constexpr float FootHeight = .09435F;
    const float height = SpikeHeights[static_cast<std::size_t>(std::clamp(level, 1, 8) - 1)];
    // Compress into the sockets rather than protruding below the floor.
    return (height + spikeOffset(level, seconds) - FootHeight) / (height - FootHeight);
}

} // namespace ian::spike_trap_model_detail
'''
Path('src/graphics/SpikeTrapModel.hpp').write_text(header)
print(f'Baked seven spike trap levels: {total} bytes, one extra draw per trap.')
