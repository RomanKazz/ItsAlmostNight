"""Bake simple cannon upgrades matching the core and turret, stdlib only.

Original meshes, muzzle and pitch pivot are preserved. Two overlays per
level: yaw-only carriage and pitched barrel. Running again replaces them.
"""
from pathlib import Path

from upgrade_mesh import Geometry, GlbAsset

asset = GlbAsset(Path('assets/models/buildings/cannon.glb'))
STEEL = (151, 173, 183)
ORANGE = (245, 92, 12)
GOLD = (242, 188, 45)
BARREL_Y = .7001184225082397

bounds = []
for level in range(2, 9):
    base, barrel = Geometry(), Geometry()
    base.ring(1, (0, .095, 0), .605, .550, .060, STEEL)
    if level >= 3:
        cheek = [(.21, -.38), (.21, .30), (.70, .30),
                 (.83, .08), (.67, -.27), (.45, -.40)]
        for side in (-1, 1):
            lo, hi = sorted((side*.480, side*.615))
            base.prism(cheek, 0, lo, hi, ORANGE)
    if level >= 4:
        barrel.ring(2, (0, BARREL_Y, -.566), .305, .230, .065, STEEL)
    if level >= 5:
        base.ring(1, (0, .125, 0), .613, .568, .036, GOLD)
    if level >= 6:
        barrel.ring(2, (0, BARREL_Y, -.623), .317, .230, .050, GOLD)
    if level >= 7:
        cheek = [(.29, -.32), (.29, .235), (.66, .235),
                 (.745, .07), (.615, -.235), (.45, -.33)]
        inset = [(.335, -.27), (.335, .185), (.625, .185),
                 (.690, .07), (.580, -.185), (.45, -.28)]
        for side in (-1, 1):
            lo, hi = sorted((side*.616, side*.644))
            base.prism(cheek, 0, lo, hi, GOLD if level == 8 else STEEL)
            lo, hi = sorted((side*.645, side*.660))
            base.prism(inset, 0, lo, hi, ORANGE)
    if level == 8:
        barrel.ring(2, (0, BARREL_Y, .190), .320, .290, .085, GOLD)
    # Keep the pair layout uniform, including levels without a barrel change.
    # A close-fitting rear band at level two gives that mesh actual geometry.
    barrel.ring(2, (0, BARREL_Y, .260), .304, .286, .055, STEEL)
    for part, suffix in ((base, 'base'), (barrel, 'barrel')):
        bounds.append(part.bounds())
        part.append(asset, f'upgrade_cannon_l{level}_{suffix}')

total = asset.write()
def vec(v):
    return '{' + ', '.join(f'{x:.6f}F' for x in v) + '}'

header = '''#pragma once

#include "buildings/CannonRig.hpp"
#include <raymath.h>

#include <algorithm>
#include <array>

namespace ian::cannon_model_detail {

// Generated by tools/generate_cannon_upgrades.py, after collider removal.
// Original pitched barrel/yaw-only carriage: 0/1; two overlays per level.
inline constexpr int MeshCount = 16;
inline constexpr std::array<BoundingBox, 14> UpgradeBounds{{
'''
header += ''.join('    {' + vec(a) + ', ' + vec(b) + '},\n' for a,b in bounds)
header += '''}};

[[nodiscard]] inline Matrix pitchTransform(float pitchRadians) {
    return MatrixMultiply(MatrixMultiply(
        MatrixTranslate(0, -static_cast<float>(CannonPitchPivotY), 0),
        MatrixRotateX(pitchRadians)),
        MatrixTranslate(0, static_cast<float>(CannonPitchPivotY), 0));
}

template <typename Emit>
void forEachUpgradePart(int requestedLevel, Emit&& emit) {
    const int level = std::clamp(requestedLevel, 1, 8);
    if (level == 1) return;
    const int base = 2 + (level - 2)*2;
    emit(base, false);
    emit(base + 1, true);
}

[[nodiscard]] inline BoundingBox partBounds(int meshIndex) {
    return UpgradeBounds[static_cast<std::size_t>(meshIndex - 2)];
}

} // namespace ian::cannon_model_detail
'''
Path('src/graphics/CannonModel.hpp').write_text(header)
print(f'Baked seven cannon levels: {total} bytes, two extra draws per cannon.')
