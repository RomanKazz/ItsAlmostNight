"""Bake broad, readable ballista upgrades matching the other defenses.

Original rig, textures and muzzle stay intact. Two meshes per level:
yaw-only carriage and pitched bow. Re-running replaces generated geometry.
"""
from pathlib import Path

from upgrade_mesh import Geometry, GlbAsset

asset = GlbAsset(Path('assets/models/weapons/crossbow.glb'))
STEEL = (151, 173, 183)
ORANGE = (245, 92, 12)
GOLD = (242, 188, 45)

def bow_band(destination, outline, width, bottom, top, color, taper=0.0):
    # The swept bow is concave: split it into convex strips instead of a
    # triangle fan, which would fill the opening in front of the string.
    outer, inner = outline[:7], list(reversed(outline[7:]))
    for i in range(6):
        strip = Geometry()
        strip.prism([(x*width,z) for x,z in
                     (outer[i],outer[i+1],inner[i+1],inner[i])],
                    1, bottom, top, color)
        for offset in range(0,len(strip.positions),9):
            triangle = []
            for vertex in range(3):
                x,y,z = strip.positions[offset+vertex*3:offset+vertex*3+3]
                y -= (y-bottom)/(top-bottom) * taper * abs(x)/(.690*width)
                triangle.append((x,y,z))
            destination.face(triangle,color)

bounds = []
for level in range(2, 9):
    base, bow = Geometry(), Geometry()
    base.ring(1, (0, .095, 0), .605, .550, .060, STEEL)
    # One broad stock binding, no small fasteners or decorative fins.
    bow.box((0, .750, .360), (.225, .230, .135), STEEL, bevel=.12)
    if level >= 3:
        cheek = [(.21, -.38), (.21, .30), (.70, .30),
                 (.83, .08), (.67, -.27), (.45, -.40)]
        for side in (-1, 1):
            lo, hi = sorted((side*.480, side*.615))
            base.prism(cheek, 0, lo, hi, ORANGE)
    if level >= 4:
        # Follow the authored bow's sweep; keep its center opening and string.
        outline = [(-.690, -.087), (-.449, -.291), (-.237, -.410),
                   (0, -.452), (.237, -.410), (.449, -.291), (.690, -.087),
                   (.577, .066), (.340, -.123), (.181, -.210),
                   (0, -.236), (-.181, -.210), (-.340, -.123), (-.577, .066)]
        width = 1.07 if level >= 7 else 1.0
        lift = .040 if level >= 7 else 0.0
        bow_band(bow, outline, width, .742, .785,
                 GOLD if level == 8 else STEEL)
        if level >= 5:
            inset = [(-.679, -.087), (-.440, -.283), (-.232, -.400),
                     (0, -.442), (.232, -.400), (.440, -.283), (.679, -.087),
                     (.564, .053), (.334, -.132), (.179, -.219),
                     (0, -.247), (-.179, -.219), (-.334, -.132), (-.564, .053)]
            bow_band(bow, inset, width, .787, .998+lift, ORANGE, taper=.065)
    if level >= 6:
        base.ring(1, (0, .125, 0), .613, .568, .036, GOLD)
    if level == 8:
        cheek = [(.29, -.32), (.29, .235), (.66, .235),
                 (.745, .07), (.615, -.235), (.45, -.33)]
        inset = [(.335, -.27), (.335, .185), (.625, .185),
                 (.690, .07), (.580, -.185), (.45, -.28)]
        for side in (-1, 1):
            lo, hi = sorted((side*.616, side*.644))
            base.prism(cheek, 0, lo, hi, GOLD)
            lo, hi = sorted((side*.645, side*.660))
            base.prism(inset, 0, lo, hi, ORANGE)
    for part, suffix in ((base, 'base'), (bow, 'bow')):
        bounds.append(part.bounds())
        part.append(asset, f'upgrade_crossbow_l{level}_{suffix}')

total = asset.write()
def vec(v):
    return '{' + ', '.join(f'{x:.6f}F' for x in v) + '}'

header = '''#pragma once

#include <raymath.h>

#include <algorithm>
#include <array>

namespace ian::crossbow_model_detail {

// Generated by tools/generate_crossbow_upgrades.py, after collider removal.
// Original pitched bow/yaw-only carriage: 0/1; two overlays per level.
inline constexpr int MeshCount = 16;
inline constexpr float PitchPivotY = 0.14931101F;
inline constexpr std::array<BoundingBox, 14> UpgradeBounds{{
'''
header += ''.join('    {' + vec(a) + ', ' + vec(b) + '},\n' for a,b in bounds)
header += '''}};

[[nodiscard]] inline Matrix pitchTransform(float pitchRadians) {
    return MatrixMultiply(MatrixMultiply(
        MatrixTranslate(0, -PitchPivotY, 0), MatrixRotateX(pitchRadians)),
        MatrixTranslate(0, PitchPivotY, 0));
}

template <typename Emit>
void forEachUpgradePart(int requestedLevel, Emit&& emit) {
    const int level = std::clamp(requestedLevel, 1, 8);
    if (level == 1) return;
    const int base = 2 + (level - 2)*2;
    emit(base, false);
    emit(base + 1, true);
}

[[nodiscard]] inline BoundingBox partBounds(int meshIndex) {
    return UpgradeBounds[static_cast<std::size_t>(meshIndex - 2)];
}

} // namespace ian::crossbow_model_detail
'''
Path('src/graphics/CrossbowModel.hpp').write_text(header)
print(f'Baked seven crossbow levels: {total} bytes, two extra draws per ballista.')
