"""Bake simple catapult upgrades with large carriage and bucket bindings.

Original throwing arm, rig, collider and projectile socket are preserved.
Each level has two overlays: yaw-only carriage and animated throwing arm.
"""
from pathlib import Path

from upgrade_mesh import Geometry, GlbAsset

asset = GlbAsset(Path('assets/models/buildings/catapult.glb'))
STEEL = (151, 173, 183)
ORANGE = (245, 92, 12)
GOLD = (242, 188, 45)
BUCKET_Z = .6370007395744324

bounds = []
for level in range(2, 9):
    base, arm = Geometry(), Geometry()
    base.ring(1, (0, .095, 0), .605, .550, .060, STEEL)
    arm.box((0, .650, -.480), (.230, .230, .145), STEEL, bevel=.12)
    if level >= 3:
        cheek = [(.21, -.38), (.21, .30), (.70, .30),
                 (.83, .08), (.67, -.27), (.45, -.40)]
        for side in (-1, 1):
            lo, hi = sorted((side*.480, side*.615))
            base.prism(cheek, 0, lo, hi, ORANGE)
    if level >= 4:
        # A single broad octagonal rim leaves the bucket opening clear.
        radius = .435 if level >= 7 else .415
        height = .105 if level >= 7 else .065
        y = .880 if level >= 7 else .865
        arm.ring(1, (0, y, BUCKET_Z), radius, .280, height,
                 GOLD if level == 8 else STEEL, segments=8)
    if level >= 5:
        arm.ring(1, (0, .620, BUCKET_Z), .375, .290, .095, ORANGE, segments=8)
    if level >= 6:
        base.ring(1, (0, .125, 0), .613, .568, .036, GOLD)
    if level == 8:
        cheek = [(.29, -.32), (.29, .235), (.66, .235),
                 (.745, .07), (.615, -.235), (.45, -.33)]
        inset = [(.335, -.27), (.335, .185), (.625, .185),
                 (.690, .07), (.580, -.185), (.45, -.28)]
        for side in (-1, 1):
            lo, hi = sorted((side*.616, side*.644))
            base.prism(cheek, 0, lo, hi, GOLD)
            lo, hi = sorted((side*.645, side*.660))
            base.prism(inset, 0, lo, hi, ORANGE)
    for part, suffix in ((base, 'base'), (arm, 'arm')):
        bounds.append(part.bounds())
        part.append(asset, f'upgrade_catapult_l{level}_{suffix}')

total = asset.write()
def vec(v):
    return '{' + ', '.join(f'{x:.6f}F' for x in v) + '}'

header = '''#pragma once

#include "buildings/CatapultRig.hpp"
#include <raymath.h>

#include <algorithm>
#include <array>

namespace ian::catapult_model_detail {

// Generated by tools/generate_catapult_upgrades.py, after collider removal.
// Original throwing arm/yaw-only carriage: 0/1; two overlays per level.
inline constexpr int MeshCount = 16;
inline constexpr std::array<BoundingBox, 14> UpgradeBounds{{
'''
header += ''.join('    {' + vec(a) + ', ' + vec(b) + '},\n' for a,b in bounds)
header += '''}};

[[nodiscard]] inline Matrix pitchTransform(float pitchRadians) {
    return MatrixMultiply(MatrixMultiply(
        MatrixTranslate(0, -static_cast<float>(CatapultPitchPivotY), 0),
        MatrixRotateX(pitchRadians)),
        MatrixTranslate(0, static_cast<float>(CatapultPitchPivotY), 0));
}

template <typename Emit>
void forEachUpgradePart(int requestedLevel, Emit&& emit) {
    const int level = std::clamp(requestedLevel, 1, 8);
    if (level == 1) return;
    const int base = 2 + (level - 2)*2;
    emit(base, false);
    emit(base + 1, true);
}

[[nodiscard]] inline BoundingBox partBounds(int meshIndex) {
    return UpgradeBounds[static_cast<std::size_t>(meshIndex - 2)];
}

} // namespace ian::catapult_model_detail
'''
Path('src/graphics/CatapultModel.hpp').write_text(header)
print(f'Baked seven catapult levels: {total} bytes, two extra draws per catapult.')
